const structural = new Set([
  'insert_rows',
  'delete_rows',
  'insert_cols',
  'delete_cols',
  'add_sheet',
  'delete_sheet',
  'rename_sheet',
])
export function hasMixedSessionOperations(operations: readonly { op: string }[]) {
  return (
    operations.some((operation) => structural.has(operation.op)) &&
    operations.some((operation) => !structural.has(operation.op))
  )
}

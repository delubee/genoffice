// Keep the dependency-free gateway's call-name rules aligned with the installed
// desktop calculation engine. Run with --check after engine dependency updates.
import { build } from 'esbuild'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const directory = await mkdtemp(join(tmpdir(), 'genoffice-builtins-'))
try {
  const outfile = join(directory, 'functions.cjs')
  await build({
    stdin: {
      contents:
        "import { ALL_IMPLEMENTED_FUNCTIONS_SET } from '@univerjs/engine-formula'; export default [...ALL_IMPLEMENTED_FUNCTIONS_SET].sort()",
      resolveDir: root,
    },
    outfile,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    logLevel: 'silent',
  })
  const functions = createRequire(import.meta.url)(outfile).default
  const { version } = JSON.parse(
    await readFile(join(root, 'node_modules/@univerjs/engine-formula/package.json'), 'utf8'),
  )
  const text = `// Generated by tools/generate-formula-builtins.mjs from @univerjs/engine-formula ${version}.\n// Data only: the gateway has no Univer runtime dependency.\nexport const builtinFormulaFunctions = new Set<string>(${JSON.stringify(functions)})\n`
  const target = join(root, 'packages/xlsx-gateway/src/domain/formula-builtins.ts')
  // Compare syntax-independent catalog values; formatting is maintained by Prettier.
  if (process.argv.includes('--check')) {
    const existing = join(directory, 'existing.cjs')
    await build({
      entryPoints: [target],
      outfile: existing,
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: 'node22',
      logLevel: 'silent',
    })
    const catalog = [...createRequire(import.meta.url)(existing).builtinFormulaFunctions]
    if (JSON.stringify(catalog) !== JSON.stringify(functions))
      throw new Error('Formula built-in catalog differs from the installed engine; regenerate it.')
  } else await writeFile(target, text)
  process.stdout.write(`Verified ${functions.length} built-in function names.\n`)
} finally {
  await rm(directory, { recursive: true, force: true })
}
